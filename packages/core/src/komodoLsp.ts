import { mkdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import type { ProjectModel } from "./model.js";
import { normalizePath } from "./sourceRoots.js";

/**
 * Komodo's project manifest (`project.properties`, `dev.elide.kotlin.api.ProjectConfiguration`), which Komodo's `komodo`
 * analyzes: one module per source set with Kotlin source roots, its classpath and the modules it depends on.
 *
 * The format is strict: module names match `[A-Za-z_][A-Za-z0-9_-]*`, every module has at least one source root, lists
 * are comma-separated (a path holding a comma cannot be listed) and unknown keys are rejected.
 */
export interface KomodoProject {
  modules: KomodoModule[];
  /** Compiler plugins the analyzed sources need, from the models: Compose, and kotlinx.serialization by its runtime. */
  plugins: { compose: boolean; serialization: boolean };
  /** Source sets left out (no Kotlin source root) and paths that cannot be listed, with the reason. */
  skipped: string[];
}

export interface KomodoModule {
  name: string;
  /** Project root and source-set module name it was emitted for. */
  project: string;
  sourceSet: string;
  sources: string[];
  depends: string[];
  /** Dependencies whose `internal` declarations it sees: a test source set's own project's non-test sets. */
  friends: string[];
  classpath: string[];
}

const SERIALIZATION_RUNTIME = /^org\.jetbrains\.kotlinx:kotlinx-serialization-core(-jvm)?:/;

/** Build the Komodo project for one or more Elide projects (a workspace and its members). */
export function emitKomodoProject(models: readonly ProjectModel[]): KomodoProject {
  const skipped: string[] = [];
  const names = new Map<string, string>();
  const taken = new Set<string>();
  const key = (project: string, module: string) => `${normalizePath(path.resolve(project))}\u0000${module}`;
  const listable = (entry: string, what: string) => {
    if (!entry.includes(",")) return true;
    skipped.push(`${what} ${entry}: a path with a comma cannot be listed`);
    return false;
  };

  const candidates = models.flatMap((model) => model.modules.map((module) => {
    const sources = module.contentRoots.flatMap((root) => root.sourceRoots)
      .filter((root) => root.kind === "source" || root.kind === "test")
      .map((root) => root.path)
      .filter((root) => listable(root, `${module.name} source`));
    return { model, module, sources: [...new Set(sources)] };
  }));
  for (const { model, module, sources } of candidates) {
    if (sources.length === 0) {
      skipped.push(`${module.name} (${model.root}): no Kotlin source root`);
      continue;
    }
    let name = module.name.replace(/[^A-Za-z0-9_-]/g, "_").replace(/^(?![A-Za-z_])/, "_");
    for (let suffix = 2; taken.has(name); suffix++) name = `${name.replace(/_\d+$/, "")}_${suffix}`;
    taken.add(name);
    names.set(key(model.root, module.name), name);
  }

  const modules: KomodoModule[] = [];
  for (const { model, module, sources } of candidates) {
    const name = names.get(key(model.root, module.name));
    if (!name) continue;
    const libraries = new Map(model.libraries.map((library) => [library.name, library.classes]));
    const classpath = module.libraries.map((library) => libraries.get(library.name))
      .filter((entry): entry is string => entry !== undefined && listable(entry, `${module.name} classpath`));
    const depends = module.moduleDeps.map((dep) => names.get(key(dep.project, dep.module))).filter((dep): dep is string => dep !== undefined);
    const kinds = new Map(model.modules.map((m) => [m.name, m.kind]));
    const friends = module.kind !== "test" ? [] : module.moduleDeps
      .filter((dep) => normalizePath(path.resolve(dep.project)) === normalizePath(path.resolve(model.root)) && kinds.get(dep.module) !== "test")
      .map((dep) => names.get(key(dep.project, dep.module))).filter((dep): dep is string => dep !== undefined);
    modules.push({ name, project: model.root, sourceSet: module.sourceSet, sources, depends: [...new Set(depends)], friends: [...new Set(friends)], classpath: [...new Set(classpath)] });
  }

  const libraries = models.flatMap((model) => model.libraries);
  return {
    modules,
    plugins: {
      compose: models.some((model) => model.kotlin.compose === true),
      // A jar's coordinate is in its display name (`Elide: group:artifact:version`); an exploded archive records it apart.
      serialization: libraries.some((library) => SERIALIZATION_RUNTIME.test(library.coordinate ?? library.name.replace(/^Elide: /, ""))),
    },
    skipped,
  };
}

/** `project.properties` text: `java.util.Properties` syntax, backslashes escaped. */
export function serializeKomodoProject(project: KomodoProject): string {
  const value = (text: string) => text.replace(/\\/g, "\\\\");
  const lines = ["# Generated by the Elide extension for komodo-lsp-k2; rewritten on every sync.", `modules=${project.modules.map((m) => m.name).join(",")}`, "cache=off"];
  for (const module of project.modules) {
    lines.push(`module.${module.name}.sources=${value(module.sources.join(","))}`);
    if (module.depends.length > 0) lines.push(`module.${module.name}.depends=${module.depends.join(",")}`);
    if (module.friends.length > 0) lines.push(`module.${module.name}.friends=${module.friends.join(",")}`);
    if (module.classpath.length > 0) lines.push(`module.${module.name}.classpath=${value(module.classpath.join(","))}`);
  }
  return `${lines.join("\n")}\n`;
}

/** Atomically write the Komodo project to `outFile`; null when no module has Kotlin sources (nothing to analyze). */
export async function writeKomodoProject(models: readonly ProjectModel[], outFile: string): Promise<KomodoProject | null> {
  const project = emitKomodoProject(models);
  if (project.modules.length === 0) return null;
  await mkdir(path.dirname(outFile), { recursive: true });
  const tmp = `${outFile}.${process.pid}.tmp`;
  await writeFile(tmp, serializeKomodoProject(project), "utf8");
  await rename(tmp, outFile);
  return project;
}
